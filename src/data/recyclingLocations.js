/* =========================================================
   GET MATERIAL FROM LATEST AI SCAN
========================================================= */

export function suggestedMaterialFromAi() {
  try {
    const raw =
      sessionStorage.getItem(
        "climatica-ai-result"
      );

    if (!raw) {
      return null;
    }

    const result =
      JSON.parse(raw);

    return result?.identified
      ? aiToMaterial[
          result.matchedWasteType
        ] ?? null
      : null;
  } catch {
    return null;
  }
}


/* =========================================================
   GOOGLE MAPS SEARCH

   Uses the organisation name and researched address.

   This does NOT claim the coordinates
   have been independently verified.
========================================================= */

export function mapsSearchUrl(location) {
  const query = [
    location.name,
    location.address,
  ]
    .filter(Boolean)
    .join(", ");

  return (
    "https://www.google.com/maps/search/?api=1&query=" +
    encodeURIComponent(query)
  );
}